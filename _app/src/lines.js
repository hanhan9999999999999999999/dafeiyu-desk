// 同一池子里不连着抽同一句
const _last = Object.create(null);

function pick(key) {
  const pool = LINES[key];
  if (!pool || pool.length === 0) return "";
  if (pool.length === 1) return pool[0];
  let v = pool[Math.floor(Math.random() * pool.length)];
  let guard = 0;
  while (v === _last[key] && guard++ < 8) {
    v = pool[Math.floor(Math.random() * pool.length)];
  }
  _last[key] = v;
  return v;
}

// 按当前钟点选场景：0–5 深夜，6–10 早上，11–13 中午，14–17 下午，18–22 晚上
function timeKey(now = new Date()) {
  const h = now.getHours();
  if (h <= 5) return "night";
  if (h <= 10) return "morning";
  if (h <= 13) return "idle";
  if (h <= 17) return "afternoon";
  if (h <= 22) return "evening";
  return "night";
}

// 按钟点选一个「没人说话时她随口说一句」的池子。
// 深夜和早上各有一半机会说对应时段的话，其余时候还是日常池。
function idleKey(now = new Date()) {
  const h = now.getHours();
  if (h <= 5) return Math.random() < 0.65 ? "night" : "idle";
  if (h <= 10) return Math.random() < 0.5 ? "morning" : "idle";
  if (h <= 17) return Math.random() < 0.3 ? "afternoon" : "idle";
  if (h <= 22) return Math.random() < 0.35 ? "evening" : "idle";
  return "night";
}

// 今天是周几（0 周日 … 6 周六）
function isWeekend(now = new Date()) {
  const d = now.getDay();
  return d === 0 || d === 6;
}

// 按她的状态挑一个池子。饿、好感低、周末都有各自的话要说。
function stateKey(pet) {
  if (!pet) return "idle";
  if (pet.hunger < 25) return "hungry";
  if (pet.favor <= 15) return "lonely";
  // 偶尔换个视角说一句：手上在干活、手边没吃的、窗外天气。
  // 概率压得低——这三池是调味，不是主食。
  const r = Math.random();
  if (r < 0.07) return "idle.work";
  if (r < 0.12) return "idle.food";
  if (r < 0.16) return "idle.weather";
  if (isWeekend()) return Math.random() < 0.4 ? "weekend" : "idle";
  return idleKey();
}

// 会「主动开口」的全部池子。闲置词缓存照这份清单预合成，
// 顺序也照这份清单：先常用、后调味，用户中途停下也不会一句都没有。
const IDLE_KEYS = [
  "idle", "longIdle", "ping", "night", "morning", "afternoon",
  "evening", "weekend", "hungry", "lonely", "stretch.yawn",
  "idle.work", "idle.food", "idle.weather",
];

// 摊平成 [{key, text}]，同一句话只出现一次（不同池子抄了同一句也只算一条）。
// 主进程拿它做预合成清单，设置页拿它算「一共多少句 / 缓存了几条」。
function idleLines() {
  const seen = Object.create(null);
  const out = [];
  for (const key of IDLE_KEYS) {
    const pool = LINES[key] || [];
    for (const text of pool) {
      if (!text || seen[text]) continue;
      seen[text] = 1;
      out.push({ key, text });
    }
  }
  return out;
}

// 池子统计：设置页要显示「闲置词一共多少句」，也方便加词时看有没有漏键。
function stats() {
  const keys = Object.keys(LINES);
  let total = 0;
  for (const k of keys) total += LINES[k].length;
  return { keys: keys.length, total, idle: idleLines().length };
}

